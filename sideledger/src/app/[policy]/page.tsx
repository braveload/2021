export async function generateMetadata({
  params,
}: {
  params: Promise<{ policy: string }>;
}) {
  const { policy } = await params;
  const doc = docs[policy];
  if (!doc) return {};
  return {
    title: `${doc.title} | 사이드장부`,
    alternates: { canonical: siteUrl + policy },
  };
}
